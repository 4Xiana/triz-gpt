def lookup_principles(improving_id: int, worsening_id: int) -> Optional[List[int]]:
    """矛盾矩阵查询：由改善参数与恶化参数查发明原则编号。

    这一步对应论文中「由固定程序完成、不属于 LLM 工作范畴」的矩阵检索。
    返回 None 表示该矩阵单元在经典矩阵中为空（Altshuller 未给出主导原则）。
    """
    key = f"{improving_id},{worsening_id}"
    val = _MATRIX_CELLS.get(key)
    return list(val) if val else None


def parameter_name(pid: int) -> str:
    return ENGINEERING_PARAMETERS[pid]["name"]


def parameter_ref(pid: int) -> Optional[Dict[str, Any]]:
    """构造一条工程参数知识引用（用于气泡 refs 展示，与结论同源）。"""
    info = ENGINEERING_PARAMETERS.get(pid)
    if not info:
        return None
    return {"type": "parameter", "ref_id": str(pid), "name": info["name"],
            "text": f"TRIZ工程参数{pid}：{info['name']}。{info['desc']}"}


def principle_info(principle_id: int) -> Dict[str, str]:
    info = INVENTIVE_PRINCIPLES[principle_id]
    return {"id": principle_id, "name": info["name"], "desc": info["desc"]}


